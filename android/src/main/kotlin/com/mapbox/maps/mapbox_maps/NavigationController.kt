  private fun convertLaneInfo(intersectionLanes: List<com.mapbox.api.directions.v5.models.IntersectionLanes>?): LaneInfo? {
    if (intersectionLanes == null || intersectionLanes.isEmpty()) {
      return null
    }

    val lanes = intersectionLanes.map { lane ->
      Lane(
        valid = lane.valid() ?: false,
        active = lane.active() ?: false,
        directions = lane.indications() ?: emptyList()
      )
    }

    val activeDirection = intersectionLanes
      .firstOrNull { it.active() == true }
      ?.indications()
      ?.firstOrNull()

    return LaneInfo(
      lanes = lanes,
      activeDirection = activeDirection
    )
  }

