  override fun setRoute(options: RouteOptions, callback: (Result<Boolean>) -> Unit) {
    try {
      Log.d(LOG_TAG, "Setting route with options")

      val coordinates = ParseUtils.parseToPoints(options.coordinates) ?: run {
        callback(Result.failure(IllegalArgumentException("Invalid coordinates")))
        return
      }

      // Build route options
      val routeOptionsBuilder = com.mapbox.api.directions.v5.models.RouteOptions.builder()
        .applyDefaultNavigationOptions()
        .coordinatesList(coordinates)

      // Apply profile
      val profile = options.profile ?: "mapbox/driving-traffic"
      routeOptionsBuilder.profile(profile)

      // Apply optional parameters
      options.alternatives?.let { routeOptionsBuilder.alternatives(it) }
      options.language?.let { routeOptionsBuilder.language(it) }
      options.voiceInstructions?.let { routeOptionsBuilder.voiceInstructions(it) }
      options.bannerInstructions?.let { routeOptionsBuilder.bannerInstructions(it) }
      options.steps?.let { routeOptionsBuilder.steps(it) }
      options.continueStraight?.let { routeOptionsBuilder.continueStraight(it) }
      options.waypointNames?.let { routeOptionsBuilder.waypointNamesList(it.split(";")) }
      options.exclude?.let { routeOptionsBuilder.exclude(it) }
      // Walking options not currently supported in this SDK version
      options.maxHeight?.let { routeOptionsBuilder.maxHeight(it) }
      options.maxWidth?.let { routeOptionsBuilder.maxWidth(it) }
      options.maxWeight?.let { routeOptionsBuilder.maxWeight(it) }

      // Add layers for proper map matching
      routeOptionsBuilder.layersList(listOf(mapboxNavigation.getZLevel(), null))

      val finalRouteOptions = routeOptionsBuilder.build()

      // Request routes
      mapboxNavigation.requestRoutes(
        finalRouteOptions,
        object : NavigationRouterCallback {
          override fun onRoutesReady(
            routes: List<NavigationRoute>,
            @RouterOrigin routerOrigin: String
          ) {
            Log.d(LOG_TAG, "Routes ready: ${routes.size} route(s)")

            if (routes.isNotEmpty()) {
              // Set the routes for navigation
              mapboxNavigation.setNavigationRoutes(routes)

              // Update state
              if (currentState == NavigationState.ACTIVE_GUIDANCE || currentState == NavigationState.FREE_DRIVE) {
                currentState = NavigationState.ACTIVE_GUIDANCE
              }
            }

            callback(Result.success(true))
          }

          override fun onFailure(
            reasons: List<RouterFailure>,
            routeOptions: com.mapbox.api.directions.v5.models.RouteOptions
          ) {
            Log.e(LOG_TAG, "Route request failed: $reasons")
            callback(Result.failure(Exception(reasons.toString())))
          }

          override fun onCanceled(
            routeOptions: com.mapbox.api.directions.v5.models.RouteOptions,
            @RouterOrigin routerOrigin: String
          ) {
            Log.d(LOG_TAG, "Route request canceled")
            callback(Result.failure(Exception("Route request canceled")))
          }
        }
      )
    } catch (e: Exception) {
      Log.e(LOG_TAG, "Failed to set route", e)
      callback(Result.failure(e))
    }
  }

  override fun clearRoute(callback: (Result<Boolean>) -> Unit) {
    try {
      mapboxNavigation.setNavigationRoutes(emptyList())
      currentProgress = null
      
      if (currentState == NavigationState.ACTIVE_GUIDANCE) {
        currentState = NavigationState.FREE_DRIVE
      }
      
      callback(Result.success(true))
    } catch (e: Exception) {
      callback(Result.failure(e))
    }
  }

  override fun getRouteAlternatives(callback: (Result<List<RouteAlternative>>) -> Unit) {
    try {
      val alternatives = currentRoutes.drop(1).mapIndexed { index, route ->
        val directionsRoute = route.directionsRoute
        RouteAlternative(
          id = "alt_$index",
          distance = directionsRoute.distance(),
          duration = directionsRoute.duration(),
          distanceDelta = null, // Would need to calculate vs primary
          durationDelta = null
        )
      }
      callback(Result.success(alternatives))
    } catch (e: Exception) {
      callback(Result.failure(e))
    }
  }

  override fun selectAlternativeRoute(routeId: String, callback: (Result<Boolean>) -> Unit) {
    try {
      // Parse the alternative index from the ID
      val index = routeId.removePrefix("alt_").toIntOrNull()?.plus(1) ?: run {
        callback(Result.failure(IllegalArgumentException("Invalid route ID")))
        return
      }

      if (index < currentRoutes.size) {
        // Reorder routes to make the selected one primary
        val selectedRoute = currentRoutes[index]
        val newRoutes = listOf(selectedRoute) + currentRoutes.filterIndexed { i, _ -> i != index }
        mapboxNavigation.setNavigationRoutes(newRoutes)
        callback(Result.success(true))
      } else {
        callback(Result.failure(IllegalArgumentException("Route not found")))
      }
    } catch (e: Exception) {
      callback(Result.failure(e))
    }
  }

