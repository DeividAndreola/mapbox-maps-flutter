  private fun updateRouteLineStyle() {
    try {
      // Build API options
      val apiOptions = MapboxRouteLineApiOptions.Builder()
        .apply {
          routeLineOptions.enableVanishingRouteLine?.let {
            vanishingRouteLineEnabled(it)
          }
        }
        .build()

      // Build view options with colors
      val viewOptions = MapboxRouteLineViewOptions.Builder(context)
        .apply {
          routeLineOptions.primaryRouteColor?.let { color ->
            // Note: Mapbox expects colors, we'll apply via resource builder
            displayRestrictedRoadSections(true)
          }
          
          routeLineBelowLayerId("road-label-navigation")
        }
        .build()

      // Recreate route line API and view
      routeLineApi = MapboxRouteLineApi(apiOptions)
      routeLineView = MapboxRouteLineView(viewOptions)

      // Re-render current routes if any
      if (currentRoutes.isNotEmpty()) {
        routeLineApi.setNavigationRoutes(currentRoutes) { value ->
          mapView.mapboxMap.style?.apply {
            routeLineView.renderRouteDrawData(this, value)
          }
        }
      }

      Log.d(LOG_TAG, "Route line style updated")
    } catch (e: Exception) {
      Log.e(LOG_TAG, "Failed to update route line style", e)
    }
  }

