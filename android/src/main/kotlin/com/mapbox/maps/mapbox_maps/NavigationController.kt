/**
 * Main navigation controller that bridges Flutter and Mapbox Navigation SDK.
 * 
 * This class implements the NavigationInterface generated by Pigeon and manages
 * all navigation-related functionality including route management, progress tracking,
 * voice instructions, camera control, and event broadcasting.
 */
@SuppressLint("VisibleForTests")
@OptIn(ExperimentalPreviewMapboxNavigationAPI::class)
class NavigationController(
  private val context: Context,
  private val mapView: MapView,
  override val lifecycle: Lifecycle,
  private val eventListener: NavigationEventListener
) : NavigationInterface, LifecycleOwner {

  // ============================================================================
  // STATE MANAGEMENT
  // ============================================================================

  private var currentState: NavigationState = NavigationState.IDLE
    set(value) {
      if (field != value) {
        field = value
        broadcastNavigationState(value)
      }
    }

  private var currentCameraMode: CameraMode = CameraMode.IDLE
  private var currentProgress: com.mapbox.navigation.base.trip.model.RouteProgress? = null
  private var currentLocation: LocationMatcherResult? = null
  private var currentRoutes: List<NavigationRoute> = emptyList()

  // ============================================================================
  // LOCATION & POSITIONING
  // ============================================================================

  private lateinit var locationComponent: LocationComponentPlugin
  private val navigationLocationProvider = NavigationLocationProvider()

  // ============================================================================
  // VISUALIZATION
  // ============================================================================

  private lateinit var maneuverApi: MapboxManeuverApi
  private lateinit var tripProgressApi: MapboxTripProgressApi
  private lateinit var routeLineApi: MapboxRouteLineApi
  private lateinit var routeLineView: MapboxRouteLineView
  private val routeArrowApi: MapboxRouteArrowApi = MapboxRouteArrowApi()
  private lateinit var routeArrowView: MapboxRouteArrowView

  // ============================================================================
  // CAMERA
  // ============================================================================

  private lateinit var navigationCamera: NavigationCamera
  private lateinit var viewportDataSource: MapboxNavigationViewportDataSource
  private val pixelDensity = Resources.getSystem().displayMetrics.density

  private val defaultOverviewPadding: EdgeInsets by lazy {
    EdgeInsets(140.0 * pixelDensity, 40.0 * pixelDensity, 120.0 * pixelDensity, 40.0 * pixelDensity)
  }

  private val defaultFollowingPadding: EdgeInsets by lazy {
    EdgeInsets(180.0 * pixelDensity, 40.0 * pixelDensity, 150.0 * pixelDensity, 40.0 * pixelDensity)
  }

  // ============================================================================
  // VOICE & AUDIO
  // ============================================================================

  private var isVoiceInstructionsMuted = false
  private lateinit var speechApi: MapboxSpeechApi
  private lateinit var voiceInstructionsPlayer: MapboxVoiceInstructionsPlayer
  private var currentVoiceLanguage: String = Locale.getDefault().language
  private var currentVoiceUnits: VoiceUnits = VoiceUnits.METRIC

  // ============================================================================
  // NAVIGATION SDK
  // ============================================================================

  private lateinit var mapboxNavigation: MapboxNavigation
  private lateinit var replayProgressObserver: ReplayProgressObserver
  private val replayRouteMapper = ReplayRouteMapper()

  // ============================================================================
  // VISUAL CUSTOMIZATION (Sprint 2)
  // ============================================================================

  private var routeLineOptions: RouteLineOptions = RouteLineOptions()
  private var maneuverArrowOptions: ManeuverArrowOptions = ManeuverArrowOptions()

  // ============================================================================
  // OBSERVERS
  // ============================================================================

  private var isProgressObserverRegistered = false
  private var isBannerObserverRegistered = false
  private var isVoiceObserverRegistered = false
  private var isRerouteObserverRegistered = false
  private var isArrivalObserverRegistered = false
  private var isOffRouteObserverRegistered = false

  // Location Observer
  private val locationObserver = object : LocationObserver {
    var firstLocationUpdateReceived = false

    override fun onNewRawLocation(rawLocation: Location) {
      // Raw location not used currently
    }

    override fun onNewLocationMatcherResult(locationMatcherResult: LocationMatcherResult) {
      currentLocation = locationMatcherResult
      val enhancedLocation = locationMatcherResult.enhancedLocation

      // Update location puck's position on the map
      navigationLocationProvider.changePosition(
        location = enhancedLocation,
        keyPoints = locationMatcherResult.keyPoints,
      )

      // Update camera position to account for new location
      viewportDataSource.onLocationChanged(enhancedLocation)
      viewportDataSource.evaluate()

      // Initial camera transition
      if (!firstLocationUpdateReceived) {
        firstLocationUpdateReceived = true
        if (currentCameraMode == CameraMode.OVERVIEW) {
          navigationCamera.requestNavigationCameraToOverview(
            stateTransitionOptions = NavigationCameraTransitionOptions.Builder()
              .maxDuration(0)
              .build()
          )
        }
      }
    }
  }

  // Route Progress Observer
  private val routeProgressObserver = RouteProgressObserver { routeProgress ->
    currentProgress = routeProgress

    // Update camera
    viewportDataSource.onRouteProgressChanged(routeProgress)
    viewportDataSource.evaluate()

    // Update maneuver arrow
    val style = mapView.mapboxMap.style
    if (style != null) {
      val maneuverArrowResult = routeArrowApi.addUpcomingManeuverArrow(routeProgress)
      routeArrowView.renderManeuverUpdate(style, maneuverArrowResult)
    }

    // Broadcast to Flutter if observer is registered
    if (isProgressObserverRegistered) {
      broadcastRouteProgress(routeProgress)
    }
  }

  // Routes Observer
  private val routesObserver = RoutesObserver { routeUpdateResult ->
    currentRoutes = routeUpdateResult.navigationRoutes

    if (routeUpdateResult.navigationRoutes.isNotEmpty()) {
      // Generate route geometries asynchronously and render them
      routeLineApi.setNavigationRoutes(routeUpdateResult.navigationRoutes) { value ->
        mapView.mapboxMap.style?.apply {
          routeLineView.renderRouteDrawData(this, value)
        }
      }

      // Update the camera position to account for the new route
      viewportDataSource.onRouteChanged(routeUpdateResult.navigationRoutes.first())
      viewportDataSource.evaluate()
    } else {
      // Remove the route line and route arrow from the map
      val style = mapView.mapboxMap.style
      if (style != null) {
        routeLineApi.clearRouteLine { value ->
          routeLineView.renderClearRouteLineValue(style, value)
        }
        routeArrowView.render(style, routeArrowApi.clearArrows())
      }

      // Remove the route reference from camera position evaluations
      viewportDataSource.clearRouteData()
      viewportDataSource.evaluate()
    }
  }

  // Banner Instructions Observer
  private val bannerInstructionsObserver = BannerInstructionsObserver { bannerInstructions ->
    if (isBannerObserverRegistered) {
      broadcastBannerInstruction(bannerInstructions)
    }
  }

  // Voice Instructions Observer
  private val voiceInstructionsObserver = VoiceInstructionsObserver { voiceInstructions ->
    if (isVoiceObserverRegistered) {
      broadcastVoiceInstruction(voiceInstructions)
    }

    // Speak the instruction
    speechApi.generate(voiceInstructions, speechCallback)
  }

  // Off-Route Observer  
  private val offRouteObserver = OffRouteObserver {
    if (isOffRouteObserverRegistered) {
      broadcastOffRoute()
    }
  }

  // Arrival Observer
  private val arrivalObserver = object : ArrivalObserver {
    override fun onWaypointArrival(routeProgress: com.mapbox.navigation.base.trip.model.RouteProgress) {
      if (isArrivalObserverRegistered) {
        val event = ArrivalEvent(
          finalDestination = false,
          waypointIndex = routeProgress.currentLegProgress?.legIndex?.toLong()
        )
        eventListener.onArrival(event) {}
      }
    }

    override fun onNextRouteLegStart(routeLegProgress: com.mapbox.navigation.base.trip.model.RouteLegProgress) {
      // Called when starting the next leg
    }

    override fun onFinalDestinationArrival(routeProgress: com.mapbox.navigation.base.trip.model.RouteProgress) {
      if (isArrivalObserverRegistered) {
        val event = ArrivalEvent(
          finalDestination = true,
          waypointIndex = routeProgress.currentLegProgress?.legIndex?.toLong()
        )
        eventListener.onArrival(event) {}
      }
    }
  }

  // Speech Callback
  private val speechCallback = MapboxNavigationConsumer<Expected<SpeechError, SpeechValue>> { expected ->
    expected.fold(
      { error ->
        // Play the instruction via fallback text-to-speech engine
        voiceInstructionsPlayer.play(error.fallback, voiceInstructionsPlayerCallback)
      },
      { value ->
        // Play the sound file from the external generator
        voiceInstructionsPlayer.play(value.announcement, voiceInstructionsPlayerCallback)
      }
    )
  }

  // Voice Player Callback
  private val voiceInstructionsPlayerCallback = MapboxNavigationConsumer<SpeechAnnouncement> { value ->
    // Remove already consumed file to free-up space
    speechApi.clean(value)
  }

  // Route line vanishing listener
  private val onPositionChangedListener = OnIndicatorPositionChangedListener { point ->
    val result = routeLineApi.updateTraveledRouteLine(point)
    mapView.mapboxMap.style?.apply {
      routeLineView.renderRouteLineUpdate(this, result)
    }
  }

  // ============================================================================
  // INITIALIZATION
  // ============================================================================

  init {
    initializeComponents()
  }

  private fun initializeComponents() {
    val mapboxMap = mapView.mapboxMap
    val camera = mapView.camera

    // Initialize viewport and camera
    viewportDataSource = MapboxNavigationViewportDataSource(mapboxMap)
    navigationCamera = NavigationCamera(mapboxMap, camera, viewportDataSource)

    // Initialize formatters
    val distanceFormatterOptions = DistanceFormatterOptions.Builder(context).build()
    maneuverApi = MapboxManeuverApi(MapboxDistanceFormatter(distanceFormatterOptions))

    tripProgressApi = MapboxTripProgressApi(
      TripProgressUpdateFormatter.Builder(context)
        .distanceRemainingFormatter(DistanceRemainingFormatter(distanceFormatterOptions))
        .timeRemainingFormatter(TimeRemainingFormatter(context))
        .percentRouteTraveledFormatter(PercentDistanceTraveledFormatter())
        .estimatedTimeOfArrivalFormatter(EstimatedTimeOfArrivalFormatter(context, TimeFormat.TWENTY_FOUR_HOURS))
        .build()
    )

    // Initialize speech
    speechApi = MapboxSpeechApi(context, currentVoiceLanguage)
    voiceInstructionsPlayer = MapboxVoiceInstructionsPlayer(context, currentVoiceLanguage)

    // Initialize route line
    val mapboxRouteLineViewOptions = MapboxRouteLineViewOptions.Builder(context)
      .routeLineBelowLayerId("road-label-navigation")
      .build()

   routeLineApi = MapboxRouteLineApi(MapboxRouteLineApiOptions.Builder().build())
    routeLineView = MapboxRouteLineView(mapboxRouteLineViewOptions)

    // Initialize maneuver arrow
    val routeArrowOptions = RouteArrowOptions.Builder(context).build()
    routeArrowView = MapboxRouteArrowView(routeArrowOptions)

    // Initialize MapboxNavigation
    MapboxNavigationApp.setup(
      com.mapbox.navigation.base.options.NavigationOptions.Builder(context)
        .routeAlternativesOptions(
          RouteAlternativesOptions.Builder()
            .intervalMillis(30.seconds.inWholeMilliseconds)
            .build()
        )
        .build()
    )

    MapboxNavigationApp.attach(this)
    mapboxNavigation = MapboxNavigationApp.current()!!

    // Register core observers
    mapboxNavigation.registerRoutesObserver(routesObserver)
    mapboxNavigation.registerLocationObserver(locationObserver)

    // Initialize replay for testing
    replayProgressObserver = ReplayProgressObserver(mapboxNavigation.mapboxReplayer)
  }

  // ============================================================================
  // NAVIGATION INTERFACE IMPLEMENTATION - SESSION MANAGEMENT
  // ============================================================================

  override fun startNavigation(options: NavigationOptions, callback: (Result<Boolean>) -> Unit) {
    try {
      Log.d(LOG_TAG, "Starting navigation with options: $options")

      // Set up location component
      locationComponent = mapView.location.apply {
        setLocationProvider(navigationLocationProvider)
        addOnIndicatorPositionChangedListener(onPositionChangedListener)
        enabled = true
      }

      // Configure viewport
      viewportDataSource.options.followingFrameOptions.defaultPitch = 35.0
      viewportDataSource.evaluate()

      // Apply camera mode
      val initialMode = options.initialCameraMode ?: CameraMode.FOLLOWING
      setCameraMode(initialMode)

      // Start trip session
      mapboxNavigation.startTripSession()

      currentState = if (currentRoutes.isEmpty()) {
        NavigationState.FREE_DRIVE
      } else {
        NavigationState.ACTIVE_GUIDANCE
      }

      callback(Result.success(true))
    } catch (e: Exception) {
      Log.e(LOG_TAG, "Failed to start navigation", e)
      callback(Result.failure(e))
    }
  }

  override fun stopNavigation(callback: (Result<Boolean>) -> Unit) {
    try {
      Log.d(LOG_TAG, "Stopping navigation")

      // Stop trip session
      mapboxNavigation.stopTripSession()

      // Clear routes
      mapboxNavigation.setNavigationRoutes(emptyList())

      // Remove location listener
      if (::locationComponent.isInitialized) {
        locationComponent.removeOnIndicatorPositionChangedListener(onPositionChangedListener)
      }

      currentState = NavigationState.STOPPED
      currentProgress = null
      currentLocation = null

      callback(Result.success(true))
    } catch (e: Exception) {
      Log.e(LOG_TAG, "Failed to stop navigation", e)
      callback(Result.failure(e))
    }
  }

  override fun pauseNavigation(callback: (Result<Boolean>) -> Unit) {
    try {
      // Mapbox Navigation doesn't have explicit pause, but we can stop guidance
      // while keeping the session alive
      mapboxNavigation.stopTripSession()
      currentState = NavigationState.IDLE
      callback(Result.success(true))
    } catch (e: Exception) {
      callback(Result.failure(e))
    }
  }

  override fun resumeNavigation(callback: (Result<Boolean>) -> Unit) {
    try {
      mapboxNavigation.startTripSession()
      currentState = if (currentRoutes.isEmpty()) {
        NavigationState.FREE_DRIVE
      } else {
        NavigationState.ACTIVE_GUIDANCE
      }
      callback(Result.success(true))
    } catch (e: Exception) {
      callback(Result.failure(e))
    }
  }

  override fun getNavigationState(): NavigationState {
    return currentState
  }

