  override fun setCameraMode(mode: CameraMode) {
    currentCameraMode = mode
    when (mode) {
      CameraMode.IDLE -> {
        // Camera doesn't follow
      }
      CameraMode.OVERVIEW -> {
        navigationCamera.requestNavigationCameraToOverview()
      }
      CameraMode.FOLLOWING -> {
        navigationCamera.requestNavigationCameraToFollowing()
      }
    }
  }

  override fun getCameraMode(): CameraMode {
    return currentCameraMode
  }

  override fun setCameraPadding(padding: CameraPadding) {
    val edgeInsets = EdgeInsets(
      padding.top * pixelDensity,
      padding.left * pixelDensity,
      padding.bottom * pixelDensity,
      padding.right * pixelDensity
    )

    viewportDataSource.overviewPadding = edgeInsets
    viewportDataSource.followingPadding = edgeInsets
    viewportDataSource.evaluate()
  }

  // ============================================================================
  // NAVIGATION INTERFACE IMPLEMENTATION - VOICE & INSTRUCTIONS
  // ============================================================================

  override fun setVoiceMuted(muted: Boolean) {
    isVoiceInstructionsMuted = muted
    if (muted) {
      voiceInstructionsPlayer.volume(SpeechVolume(0f))
    } else {
      voiceInstructionsPlayer.volume(SpeechVolume(1f))
    }
  }

  override fun isVoiceMuted(): Boolean {
    return isVoiceInstructionsMuted
  }

  override fun setVoiceLanguage(languageCode: String) {
    if (currentVoiceLanguage != languageCode) {
      currentVoiceLanguage = languageCode
      
      // Recreate speech API and player with new language
      speechApi.cancel()
      voiceInstructionsPlayer.shutdown()
      
      speechApi = MapboxSpeechApi(context, languageCode)
      voiceInstructionsPlayer = MapboxVoiceInstructionsPlayer(context, languageCode)
      
      if (isVoiceInstructionsMuted) {
        voiceInstructionsPlayer.volume(SpeechVolume(0f))
      }
    }
  }

  override fun setVoiceUnits(units: VoiceUnits) {
    currentVoiceUnits = units
    // Voice units are applied during route request
  }

  // ============================================================================
  // NAVIGATION INTERFACE IMPLEMENTATION - EVENT REGISTRATION
  // ============================================================================

  override fun registerProgressObserver() {
    if (!isProgressObserverRegistered) {
      mapboxNavigation.registerRouteProgressObserver(routeProgressObserver)
      mapboxNavigation.registerRouteProgressObserver(replayProgressObserver)
      isProgressObserverRegistered = true
    }
  }

  override fun unregisterProgressObserver() {
    if (isProgressObserverRegistered) {
      mapboxNavigation.unregisterRouteProgressObserver(routeProgressObserver)
      mapboxNavigation.unregisterRouteProgressObserver(replayProgressObserver)
      isProgressObserverRegistered = false
    }
  }

  override fun registerBannerObserver() {
    if (!isBannerObserverRegistered) {
      mapboxNavigation.registerBannerInstructionsObserver(bannerInstructionsObserver)
      isBannerObserverRegistered = true
    }
  }

  override fun unregisterBannerObserver() {
    if (isBannerObserverRegistered) {
      mapboxNavigation.unregisterBannerInstructionsObserver(bannerInstructionsObserver)
      isBannerObserverRegistered = false
    }
  }

  override fun registerVoiceObserver() {
    if (!isVoiceObserverRegistered) {
      mapboxNavigation.registerVoiceInstructionsObserver(voiceInstructionsObserver)
      isVoiceObserverRegistered = true
    }
  }

  override fun unregisterVoiceObserver() {
    if (isVoiceObserverRegistered) {
      mapboxNavigation.unregisterVoiceInstructionsObserver(voiceInstructionsObserver)
      isVoiceObserverRegistered = false
    }
  }

  override fun registerRerouteObserver() {
    // Reroute detection is automatic in Mapbox Navigation SDK
    // Events will be broadcast through routes observer
    isRerouteObserverRegistered = true
  }

  override fun unregisterRerouteObserver() {
    isRerouteObserverRegistered = false
  }

  override fun registerArrivalObserver() {
    if (!isArrivalObserverRegistered) {
      mapboxNavigation.registerArrivalObserver(arrivalObserver)
      isArrivalObserverRegistered = true
    }
  }

  override fun unregisterArrivalObserver() {
    if (isArrivalObserverRegistered) {
      mapboxNavigation.unregisterArrivalObserver(arrivalObserver)
      isArrivalObserverRegistered = false
    }
  }

  override fun registerOffRouteObserver() {
    if (!isOffRouteObserverRegistered) {
      mapboxNavigation.registerOffRouteObserver(offRouteObserver)
      isOffRouteObserverRegistered = true
    }
  }

  override fun unregisterOffRouteObserver() {
    if (isOffRouteObserverRegistered) {
      mapboxNavigation.unregisterOffRouteObserver(offRouteObserver)
      isOffRouteObserverRegistered = false
    }
  }

