  private fun convertRouteProgress(progress: com.mapbox.navigation.base.trip.model.RouteProgress): RouteProgress {
    val currentLegProgress = progress.currentLegProgress
    val currentStepProgress = currentLegProgress?.currentStepProgress

    return RouteProgress(
      distanceRemaining = progress.distanceRemaining.toDouble(),
      durationRemaining = progress.durationRemaining,
      distanceTraveled = progress.distanceTraveled.toDouble(),
      fractionTraveled = progress.fractionTraveled.toDouble(),
      currentStepIndex = currentStepProgress?.stepIndex?.toLong(),
      currentLegIndex = progress.currentLegProgress?.legIndex?.toLong(),
      upcomingStepIndex = currentStepProgress?.stepIndex?.plus(1)?.toLong(),
      currentStep = currentStepProgress?.step?.let { convertRouteStep(it, currentStepProgress) },
      upcomingStep = null, // Would need to get from route
      currentRoadName = currentStepProgress?.step?.name(),
      currentSpeedLimit = null, // Speed limit requires SpeedLimitObserver registration
      congestionLevel = null // Would need congestion data from route
    )
  }

  private fun convertRouteStep(
    step: com.mapbox.api.directions.v5.models.LegStep,
    stepProgress: com.mapbox.navigation.base.trip.model.RouteStepProgress
  ): RouteStep {
    // Extract lane info from first intersection
    val laneInfo = step.intersections()?.firstOrNull()?.lanes()?.let { convertLaneInfo(it) }

    return RouteStep(
      distance = step.distance(),
      duration = step.duration(),
      name = step.name(),
      instruction = step.maneuver().instruction(),
      maneuverType = convertManeuverType(step.maneuver().type()),
      maneuverModifier = convertManeuverModifier(step.maneuver().modifier()),
      distanceToManeuver = stepProgress.distanceRemaining.toDouble(),
      estimatedTimeToManeuver = stepProgress.durationRemaining,
      exitNumbers = step.exits(),
      laneInfo = laneInfo
    )
  }

  private fun convertManeuverType(type: String?): ManeuverType? {
    return when (type) {
      "turn" -> ManeuverType.TURN
      "new name" -> ManeuverType.NEW_NAME
      "depart" -> ManeuverType.DEPART
      "arrive" -> ManeuverType.ARRIVE
      "merge" -> ManeuverType.MERGE
      "on ramp" -> ManeuverType.ON_RAMP
      "off ramp" -> ManeuverType.OFF_RAMP
      "fork" -> ManeuverType.FORK
      "end of road" -> ManeuverType.END_OF_ROAD
      "continue" -> ManeuverType.CONTINUE_
      "roundabout" -> ManeuverType.ROUNDABOUT
      "rotary" -> ManeuverType.ROTARY
      "roundabout turn" -> ManeuverType.ROUNDABOUT_TURN
      "notification" -> ManeuverType.NOTIFICATION
      "exit roundabout" -> ManeuverType.EXIT_ROUNDABOUT
      "exit rotary" -> ManeuverType.EXIT_ROTARY
      else -> null
    }
  }

  private fun convertManeuverModifier(modifier: String?): ManeuverModifier? {
    return when (modifier) {
      "uturn" -> ManeuverModifier.UTURN
      "sharp right" -> ManeuverModifier.SHARP_RIGHT
      "right" -> ManeuverModifier.RIGHT
      "slight right" -> ManeuverModifier.SLIGHT_RIGHT
      "straight" -> ManeuverModifier.STRAIGHT
      "slight left" -> ManeuverModifier.SLIGHT_LEFT
      "left" -> ManeuverModifier.LEFT
      "sharp left" -> ManeuverModifier.SHARP_LEFT
      else -> null
    }
  }

  private fun convertEnhancedLocation(result: LocationMatcherResult): EnhancedLocation {
    val location = result.enhancedLocation
    return EnhancedLocation(
      latitude = location.latitude,
      longitude = location.longitude,
      bearing = location.bearing?.toDouble(),
      speed = location.speed?.toDouble(),
      altitude = location.altitude,
      accuracy = location.horizontalAccuracy?.toDouble(),
      timestamp = location.timestamp?.toLong(),
      isMatched = result.isTeleport.not(),
      roadName = null // Would need to get from current step
    )
  }

